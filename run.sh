#!/bin/bash

# --- НАСТРОЙКА ЦВЕТОВ ДЛЯ ВЫВОДА В КОНСОЛЬ ---
GREEN='\033[0m\033[32m'
YELLOW='\033[0m\033[33m'
RED='\033[0m\033[31m'
NC='\033[0m' # Без цвета

echo -e "${YELLOW}[1/4] Останавливаем и удаляем старые контейнеры...${NC}"
# Останавливаем проект и удаляем связанные контейнеры, но сохраняем данные (volumes)
docker compose down

echo -e "${YELLOW}[2/4] Проверяем наличие файла конфигурации .env...${NC}"
# Проверка существования файла .env до начала сборки
if [ ! -f .env ]; then
    echo -e "${RED}[ОШИБКА] Файл .env не найден! Пожалуйста, создайте его перед запуском.${NC}"
    exit 1
fi

echo -e "${YELLOW}[3/4] Собираем и запускаем Docker-контейнеры в фоновом режиме...${NC}"
# Флаг --build гарантирует, что Docker пересоберет образы с новым кодом
docker compose up --build -d

# Проверяем статус выполнения предыдущей команды
if [ $? -eq 0 ]; then
    echo -e "${GREEN}[УСПЕШНО] Проект успешно запущен!${NC}"
    echo -e "${GREEN}Frontend доступен по порту, указанному в FRONTEND_PORT (по умолчанию: http://localhost:80)${NC}"
    echo -e "${GREEN}Backend доступен по порту, указанному в BACKEND_PORT (по умолчанию: http://localhost:8080)${NC}"
else
    echo -e "${RED}[ОШИБКА] Не удалось запустить проект. Проверьте логи Docker.${NC}"
    exit 1
fi

echo -e "${YELLOW}[4/4] Выводим логи запущенных контейнеров (Нажмите Ctrl+C для выхода)...${NC}"
# Отслеживание логов в реальном времени
docker compose logs -f

